// Bundles kits/templates/*.html into kits/templates.js so the studio can start
// a new game from a template without any server step. Run after editing a
// template:  node kits/generate.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const dir = dirname(fileURLToPath(import.meta.url))
const templates = {}
for (const file of readdirSync(join(dir, 'templates')).filter((f) => f.endsWith('.html')).sort()) {
  templates[file.replace(/\.html$/, '')] = readFileSync(join(dir, 'templates', file), 'utf8')
}
writeFileSync(join(dir, 'templates.js'), `// Generated by kits/generate.mjs from kits/templates/*.html. Do not edit.\nexport const TEMPLATES = ${JSON.stringify(templates, null, 0)}\n`)
console.log('templates:', Object.keys(templates).join(', '))
